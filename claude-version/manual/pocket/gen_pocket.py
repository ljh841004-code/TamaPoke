def shot(name, small=False):
    return '<div class="shot"><img src="img/%s.png"></div>' % name


def two(a, b, ca='', cb=''):
    c = ''
    if ca or cb:
        c = '<div class="two cap"><span>%s</span><span>%s</span></div>' % (ca, cb)
    return '<div class="two">%s%s</div>%s' % (shot(a, True), shot(b, True), c)


def ul(*items):
    return '<ul>' + ''.join('<li>%s</li>' % i for i in items) + '</ul>'


def tip(t):
    return '<div class="tip">%s</div>' % t


def table(rows, head=None):
    h = ''
    if head:
        h = '<tr>' + ''.join('<th>%s</th>' % x for x in head) + '</tr>'
    body = ''.join('<tr>' + ''.join(('<th>%s</th>' if i == 0 else '<td>%s</td>') % c for i, c in enumerate(r)) + '</tr>'
                   for r in rows)
    return '<table>%s%s</table>' % (h, body)


